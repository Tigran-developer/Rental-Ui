#!/usr/bin/env node
// Regenerates src/app/build-info.ts with a fresh per-build stamp.
//
// Why: translations are fetched at runtime from /i18n/{lang}.json (see
// app.config.ts). Production nginx sends no Cache-Control for those files,
// so browsers heuristically cache them and can keep serving a stale copy for
// days after a deploy, even though index.html/JS are correctly busted. This
// script gives the i18n request URL a query param that changes on every
// build, so it's a brand-new URL the browser has never cached.
//
// Runs as the npm `prebuild`/`pretest` lifecycle hook (see package.json), so
// `npm run build` and `npm test` always regenerate this file first. Falls
// back to a timestamp when git isn't available (e.g. the Docker build stage
// for the UI image has no .git directory), so BUILD_STAMP is always a
// non-empty value — never a literal "undefined".
//
// The checked-in src/app/build-info.ts is only a safe fallback for the case
// where something invokes `ng build`/`ng test` directly, bypassing the npm
// lifecycle hooks above.
const { execSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

function resolveStamp() {
  // Always fold in a timestamp component: this must change on every build,
  // including two rebuilds of the exact same commit (e.g. a re-run CI job
  // or a local rebuild with no new commit in between) — a bare git SHA
  // would stay identical across those and fail to bust the browser cache.
  const timestamp = Date.now().toString(36);
  try {
    const sha = execSync('git rev-parse --short HEAD', {
      stdio: ['ignore', 'pipe', 'ignore'],
    })
      .toString()
      .trim();
    if (sha) return `${sha}-${timestamp}`;
  } catch {
    // git not installed, not a repo, or no commits yet (e.g. the Docker
    // build stage for the UI image has no .git directory) — fall through
    // to the timestamp-only fallback below.
  }
  return timestamp;
}

const stamp = resolveStamp();
const filePath = path.join(__dirname, '..', 'src', 'app', 'build-info.ts');
const content = `// AUTO-GENERATED by scripts/generate-build-info.js — do not edit by hand.
// Regenerated on every build via the npm prebuild/pretest hook. The value
// checked into git is only the fallback used when this script hasn't run
// (see script header comment for why it exists and how it's wired in).
export const BUILD_STAMP = '${stamp}';
`;

fs.writeFileSync(filePath, content);
console.log(`[generate-build-info] BUILD_STAMP=${stamp}`);
